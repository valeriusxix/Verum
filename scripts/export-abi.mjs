// Writes the VerumRegistry ABI from Foundry's build output to packages/shared/abi.ts (typed `as const`
// for viem/wagmi). Run via `pnpm abi`, which builds the contracts first.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const artifact = JSON.parse(
  readFileSync(`${root}contracts/out/VerumRegistry.sol/VerumRegistry.json`, 'utf8'),
);

const out = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand; run \`pnpm abi\`.
export const verumRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(`${root}packages/shared/abi.ts`, out);
console.log(`abi.ts: ${artifact.abi.length} entries`);
